const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("versions", {
  node: () => process.versions.node,
  chrome: () => process.versions.chrome,
  electron: () => process.versions.electron,
  ping: () => ipcRenderer.invoke("ping"),
  // we can also expose variables, not just functions
});

contextBridge.exposeInMainWorld("api", {
  openFile: () => ipcRenderer.invoke("file:open"),
  saveData: (data) => ipcRenderer.invoke("data:save", data),
  getLatestData: () => ipcRenderer.invoke("data:latest"),
  querySalesData: (options) => ipcRenderer.invoke("data:query", options),
  getDailySalesTrend: (options) => ipcRenderer.invoke("dashboard:sales-daily", options),
  saveFileAs: (file) => ipcRenderer.invoke("file:save-as", file),
  saveGeneratedFiles: (payload) => ipcRenderer.invoke("files:save-generated", payload),
  openFileLocation: (filePath) => ipcRenderer.invoke("files:open-location", filePath),
  getDatabaseHealth: () => ipcRenderer.invoke("db:health"),
  getDatabaseSummary: () => ipcRenderer.invoke("db:summary"),
  addEvent: (event) => ipcRenderer.invoke("events:add", event),
  getEvents: () => ipcRenderer.invoke("events:list"),
  listNotifications: (options) => ipcRenderer.invoke("notifications:list", options),
  addNotification: (payload) => ipcRenderer.invoke("notifications:add", payload),
  markNotificationRead: (notificationId) => ipcRenderer.invoke("notifications:mark-read", notificationId),
  clearNotifications: () => ipcRenderer.invoke("notifications:clear"),
  getRecentFiles: () => ipcRenderer.invoke("recent-files:get"),
  getMasterData: () => ipcRenderer.invoke("master-data:get"),
  importContacts: (contacts) => ipcRenderer.invoke("contacts:import", contacts),
  getMessageTemplates: () => ipcRenderer.invoke("message-templates:get"),
  getSendPackages: () => ipcRenderer.invoke("send-packages:get"),
  prepareSendPackageAttachments: (packageId) => ipcRenderer.invoke("send-packages:prepare-attachments", packageId),
  updateSendPackageItemStatus: (payload) => ipcRenderer.invoke("send-package-items:update-status", payload),
  getDepartmentRequests: () => ipcRenderer.invoke("department-requests:list"),
  getClosingCompanies: () => ipcRenderer.invoke("closing-companies:list"),
  saveClosingCompanies: (rows) => ipcRenderer.invoke("closing-companies:save", rows),
  getAppSettings: () => ipcRenderer.invoke("app-settings:get"),
  saveAppSettings: (settings) => ipcRenderer.invoke("app-settings:save", settings),
  chooseDirectory: (options) => ipcRenderer.invoke("app-settings:choose-directory", options),
  chooseFile: (options) => ipcRenderer.invoke("app-settings:choose-file", options),
  showNotification: (payload) => ipcRenderer.invoke("notifications:show", payload),
  sendGmailTest: (payload) => ipcRenderer.invoke("gmail:send-test", payload),
  listBackups: () => ipcRenderer.invoke("backups:list"),
  createBackup: (payload) => ipcRenderer.invoke("backups:create", payload),
  restoreBackup: (payload) => ipcRenderer.invoke("backups:restore", payload),
});
